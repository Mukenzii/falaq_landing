#!/usr/bin/env node
// Uzum Market → website sync.
//
// Fetches the shop's products from Uzum, keeps only public fields (title, image, price, in stock),
// matches them to the site's books and writes `uzum.js`. The site reads price and stock from that
// file. The API key never ends up in the file or on the site.
//
// Run:          node scripts/sync-uzum.mjs            (or: npm run sync:uzum)
// Report only:  node scripts/sync-uzum.mjs --dry-run  (does not write the file)
//
// Keys are read from `.env` (see .env.example).

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";
import { UzumClient, UzumApiError } from "./uzum-client.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_FILE = join(ROOT, "uzum.js");
const DRY_RUN = process.argv.includes("--dry-run");

// Statuses that are not shown on the site at all
const HIDDEN = new Set(["ARCHIVED", "DELETED", "PERM_BANNED"]);
// Statuses that are shown but cannot be bought
const NOT_BUYABLE = new Set(["NO_SKU", "RUN_OUT", "BLOCKED", "SKU_BLOCKED", "NOT_READY_TO_SEND", ...HIDDEN]);

main().catch((e) => {
  console.error(`\n✗ ${e instanceof UzumApiError ? e.message : e.stack || e}`);
  process.exit(1);
});

async function main() {
  loadEnv(join(ROOT, ".env"));
  const client = new UzumClient({
    key: process.env.UZUM_API_KEY,
    base: process.env.UZUM_API_BASE || "https://api-seller.uzum.uz/api/seller-openapi",
  });

  // 1. Shop
  let shopId = process.env.UZUM_SHOP_ID?.trim();
  let shopName = null;
  const shops = await client.shops();
  if (!shops.length) throw new UzumApiError("This key does not see any shops.", { kind: "auth" });
  if (shopId) {
    shopName = shops.find((s) => String(s.id) === shopId)?.name ?? null;
    if (!shopName) console.warn(`! UZUM_SHOP_ID=${shopId} is not among this key's shops. Available: ${shops.map((s) => `${s.id} (${s.name})`).join(", ")}`);
  } else {
    if (shops.length > 1) {
      console.log("The account has several shops; using the first one. Set UZUM_SHOP_ID in .env to pick another:");
      for (const s of shops) console.log(`  ${s.id}  ${s.name}`);
    }
    shopId = String(shops[0].id);
    shopName = shops[0].name;
  }
  console.log(`Shop: ${shopName ?? "?"} (${shopId})`);

  // 2. Products
  const raw = await client.allProducts(shopId);
  const products = raw.map(toPublic).filter((p) => p && !HIDDEN.has(p.status));
  console.log(`Products: ${raw.length} fetched, ${products.length} will be shown on the site.`);

  // 3. Match to the site's books
  const books = loadBooks();
  const matches = matchBooks(books, products);

  // 4. Report
  const byId = new Map(products.map((p) => [p.id, p]));
  console.log("\nBook ↔ Uzum product:");
  for (const b of books) {
    const p = byId.get(matches[b.slug]);
    console.log(p
      ? `  ✓ ${b.title.padEnd(28)} → ${p.id}  ${formatSum(p.price)}  ${p.inStock ? "in stock" : "sold out"}`
      : `  – ${b.title.padEnd(28)} → not found (set uzumId in data.js)`);
  }
  const used = new Set(Object.values(matches));
  const extra = products.filter((p) => !used.has(p.id));
  if (extra.length) {
    console.log("\nUzum products not on the site (add them to data.js if needed):");
    for (const p of extra) console.log(`  ${p.id}  ${p.title}  ${formatSum(p.price)}`);
  }
  if (client.dailyRemaining != null) console.log(`\nDaily quota remaining: ${client.dailyRemaining}`);

  // 5. Write
  const data = {
    generatedAt: new Date().toISOString(),
    shop: { id: Number(shopId), name: shopName },
    books: matches,
    products,
  };
  const file =
    "/* Generated by scripts/sync-uzum.mjs. Do not edit by hand. */\n" +
    `window.UZUM = ${JSON.stringify(data, null, 2)};\n`;
  if (DRY_RUN) {
    console.log("\n--dry-run: uzum.js was not written.");
  } else {
    writeFileSync(OUT_FILE, file);
    console.log(`\n✓ uzum.js updated (${products.length} products, ${Object.keys(matches).length} books matched).`);
  }
}

/* ---------- Public fields only ---------- */
function toPublic(p) {
  const id = Number(p.productId ?? p.id);
  if (!id) return null;
  const skus = (p.skuList ?? []).filter((s) => !s.archived);
  const priceOf = (list) => list.map((s) => Number(s.price)).filter((n) => Number.isFinite(n) && n > 0);
  // Cheapest variant that is in stock; if every variant is sold out, the cheapest overall.
  const available = skus.filter((s) => (Number(s.quantityActive) || 0) + (Number(s.quantityFbs) || 0) > 0);
  const prices = priceOf(available).length ? priceOf(available) : priceOf(skus);
  const sum = (key) => skus.reduce((t, s) => t + (Number(s[key]) || 0), 0);
  const qty = (Number(p.quantityActive ?? sum("quantityActive")) || 0) + (Number(p.quantityFbs ?? sum("quantityFbs")) || 0);
  const status = p.status?.value ?? p.status ?? null;
  const title = String(p.title ?? "").trim();
  const rating = Number.parseFloat(p.rating);
  return {
    id,
    title,
    category: p.category ?? null,
    image: p.image || p.previewImg || skus[0]?.previewImage || null,
    rating: Number.isFinite(rating) && rating > 0 ? rating : null,
    price: prices.length ? Math.min(...prices) : null,
    inStock: qty > 0 && !NOT_BUYABLE.has(status) && prices.length > 0,
    status,
    url: `https://uzum.uz/uz/product/${urlSlug(title)}-${id}`,
  };
}

/* ---------- Book matching ---------- */
// 1) A book with uzumId in data.js uses that product.
// 2) Otherwise by title: the book title must appear as whole words in the Uzum title
//    (Cyrillic is transliterated to Latin first). Each product goes to the book with the longest
//    matching title, so a "Binafsha shu'lasi II" product lands on part two, not part one.
function matchBooks(books, products) {
  const result = {};
  const ids = new Set(products.map((p) => p.id));
  for (const b of books) if (b.uzumId && ids.has(Number(b.uzumId))) result[b.slug] = Number(b.uzumId);

  const free = books.filter((b) => !result[b.slug]);
  const candidates = {};
  for (const p of products) {
    const t = ` ${normalize(p.title)} `;
    let best = null;
    for (const b of free) {
      const n = normalize(b.title);
      if (n && t.includes(` ${n} `) && (!best || n.length > normalize(best.title).length)) best = b;
    }
    if (best) (candidates[best.slug] ||= []).push(p);
  }
  for (const [slug, list] of Object.entries(candidates)) {
    list.sort((a, b) => Number(b.inStock) - Number(a.inStock));
    result[slug] = list[0].id;
  }
  return result;
}

// Uzbek Cyrillic → Latin
const CYR = {
  а: "a", б: "b", в: "v", г: "g", ғ: "g", д: "d", е: "e", ё: "yo", ж: "j", з: "z", и: "i", й: "y",
  к: "k", қ: "q", л: "l", м: "m", н: "n", о: "o", п: "p", р: "r", с: "s", т: "t", у: "u", ў: "o",
  ф: "f", х: "x", ҳ: "h", ц: "s", ч: "ch", ш: "sh", щ: "sh", ъ: "", ь: "", ы: "i", э: "e", ю: "yu", я: "ya",
};
function normalize(s) {
  return String(s)
    .toLowerCase()
    .replace(/[Ѐ-ӿ]/g, (c) => CYR[c] ?? c)
    .replace(/[’‘ʻʼ'`]/g, "")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}
const urlSlug = (s) => normalize(s).replace(/ /g, "-") || "product";
const formatSum = (n) => (n == null ? "no price" : `${n.toLocaleString("ru-RU").replace(/ /g, " ")} so'm`);

/* ---------- Helpers ---------- */
function loadBooks() {
  const sandbox = { window: {} };
  vm.runInNewContext(readFileSync(join(ROOT, "data.js"), "utf8"), sandbox);
  return sandbox.window.FALAQ.books;
}

// Minimal .env reader: KEY=VALUE, # comments, quoted values.
// Variables already set in the environment win (e.g. CI secrets).
function loadEnv(path) {
  if (!existsSync(path)) return;
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (!m || line.trim().startsWith("#")) continue;
    let value = m[2];
    if (/^(['"]).*\1$/.test(value)) value = value.slice(1, -1);
    else value = value.replace(/\s+#.*$/, "");
    if (process.env[m[1]] === undefined) process.env[m[1]] = value;
  }
}
